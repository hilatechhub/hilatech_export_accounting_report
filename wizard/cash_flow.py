# -*- coding: utf-8 -*-
import io
from odoo import fields, models, _
from odoo.exceptions import UserError

try:
    import xlsxwriter
except ImportError:
    xlsxwriter = None


class CashFlowXlsx(models.TransientModel):
    """Export XLSX pour le wizard Cash Flow Statement."""

    _inherit = 'cash.flow.report'

    def action_export_xlsx(self):
        self.ensure_one()
        if xlsxwriter is None:
            raise UserError(_("La bibliothèque Python 'xlsxwriter' est requise."))

        data = {'ids': self.env.context.get('active_ids', []),
                'model': self.env.context.get('active_model', 'ir.ui.menu'),
                'form': self.read([
                    'date_from', 'enable_filter', 'debit_credit', 'date_to',
                    'account_report_id', 'target_move', 'company_id',
                    'journal_ids', 'label_filter', 'filter_cmp',
                    'date_from_cmp', 'date_to_cmp',
                ])[0]}
        used_context = self._build_contexts(data)
        data['form']['used_context'] = dict(
            used_context, lang=self.env.context.get('lang') or 'en_US')
        data['form']['comparison_context'] = self._build_comparison_context(data)

        report_env = self.env[
            'report.base_accounting_kit.report_cash_flow']
        report_lines = report_env.get_account_lines(data['form'])

        report_name = (data['form']['account_report_id'][1]
                       if data['form'].get('account_report_id')
                       else _('Cash Flow Statement'))
        debit_credit = data['form'].get('debit_credit')
        enable_filter = data['form'].get('enable_filter')
        label_filter = data['form'].get('label_filter') or _('Comparison')

        output = io.BytesIO()
        workbook = xlsxwriter.Workbook(output, {'in_memory': True})
        helper = self.env['hilatech.xlsx.report.helper']
        formats = helper._xlsx_get_formats(workbook)

        sheet = workbook.add_worksheet(report_name[:31])
        sheet.hide_gridlines(2)

        ncols = 2
        if debit_credit:
            ncols += 2
        if enable_filter:
            ncols += 1

        sheet.set_column(0, 0, 55)
        sheet.set_column(1, ncols - 1, 18)

        journal_codes = [j.code for j in self.env['account.journal'].browse(
            data['form'].get('journal_ids') or [])]
        info = helper._xlsx_standard_info_pairs(data['form'], journal_codes)
        info.insert(0, (_('Report'), report_name))
        row = helper._xlsx_write_header(workbook, sheet, formats,
                                         report_name, info, ncols)

        headers = [_('Name')]
        if debit_credit:
            headers += [_('Debit'), _('Credit')]
        headers.append(_('Balance'))
        if enable_filter:
            headers.append(label_filter)
        row = helper._xlsx_write_table_header(sheet, row, headers, formats)

        for line in report_lines:
            level = line.get('level') or 1
            name = line.get('name', '')
            indent = '    ' * max(level - 1, 0)
            label = f'{indent}{name}'

            if level == 1:
                fmt_text, fmt_num = formats['level_1'], formats['level_1_num']
            elif level == 2:
                fmt_text, fmt_num = formats['level_2'], formats['level_2_num']
            elif level == 3:
                fmt_text, fmt_num = formats['level_3'], formats['level_3_num']
            else:
                fmt_text, fmt_num = formats['detail'], formats['detail_num']

            sheet.write(row, 0, label, fmt_text)
            col = 1
            if debit_credit:
                sheet.write_number(row, col,
                                   float(line.get('debit') or 0.0), fmt_num)
                col += 1
                sheet.write_number(row, col,
                                   float(line.get('credit') or 0.0), fmt_num)
                col += 1
            sheet.write_number(row, col,
                               float(line.get('balance') or 0.0), fmt_num)
            col += 1
            if enable_filter:
                sheet.write_number(row, col,
                                   float(line.get('balance_cmp') or 0.0),
                                   fmt_num)
            row += 1

        row += 1
        sheet.merge_range(row, 0, row, ncols - 1,
                          _('Generated by Odoo — Hilatech Export Accounting Report'),
                          formats['footer'])

        workbook.close()
        xlsx_bytes = output.getvalue()
        output.close()

        filename = helper._xlsx_build_filename(report_name, data['form'])
        return helper._xlsx_build_attachment_action(filename, xlsx_bytes)
