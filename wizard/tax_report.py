# -*- coding: utf-8 -*-
import io
from odoo import models, _
from odoo.exceptions import UserError
from odoo.tools.misc import get_lang

try:
    import xlsxwriter
except ImportError:
    xlsxwriter = None


class TaxReportXlsx(models.TransientModel):
    """Export XLSX pour le wizard Tax Report."""

    _inherit = 'kit.account.tax.report'

    def action_export_xlsx(self):
        self.ensure_one()
        if xlsxwriter is None:
            raise UserError(_("La bibliothèque Python 'xlsxwriter' est requise."))

        data = {'ids': self.env.context.get('active_ids', []),
                'model': self.env.context.get('active_model', 'ir.ui.menu'),
                'form': self.read(['date_from', 'date_to', 'journal_ids',
                                    'target_move', 'company_id'])[0]}
        used_context = self._build_contexts(data)
        data['form']['used_context'] = dict(
            used_context, lang=get_lang(self.env).code)

        report_env = self.env['report.base_accounting_kit.report_tax']
        groups = report_env.with_context(
            data['form'].get('used_context', {})).get_lines(data['form'])

        journal_codes = [j.code for j in self.env['account.journal'].browse(
            data['form'].get('journal_ids') or [])]
        return self._build_xlsx(data['form'], groups, journal_codes)

    def _build_xlsx(self, data_form, groups, journal_codes):
        output = io.BytesIO()
        workbook = xlsxwriter.Workbook(output, {'in_memory': True})
        helper = self.env['hilatech.xlsx.report.helper']
        formats = helper._xlsx_get_formats(workbook)

        report_name = _('Tax Report')
        sheet = workbook.add_worksheet(report_name[:31])
        sheet.hide_gridlines(2)

        sheet.set_column(0, 0, 45)
        sheet.set_column(1, 2, 18)
        ncols = 3

        info = helper._xlsx_standard_info_pairs(data_form, journal_codes)
        row = helper._xlsx_write_header(workbook, sheet, formats,
                                         report_name, info, ncols)

        section_labels = [
            ('sale', _('Sales')),
            ('purchase', _('Purchases')),
        ]
        for key, label in section_labels:
            taxes = sorted(groups.get(key) or [],
                           key=lambda t: float(t.get('tax') or 0.0),
                           reverse=True)
            sheet.merge_range(row, 0, row, ncols - 1, label,
                              formats['level_1'])
            row += 1
            headers = [_('Tax Name'), _('Net'), _('Tax')]
            row = helper._xlsx_write_table_header(sheet, row, headers, formats)

            total_net = 0.0
            total_tax = 0.0
            for tax in taxes:
                sheet.write(row, 0, tax.get('name') or '', formats['detail'])
                sheet.write_number(row, 1, float(tax.get('net') or 0.0),
                                   formats['detail_num'])
                sheet.write_number(row, 2, float(tax.get('tax') or 0.0),
                                   formats['detail_num'])
                total_net += float(tax.get('net') or 0.0)
                total_tax += float(tax.get('tax') or 0.0)
                row += 1
            sheet.write(row, 0, _('Total %s') % label, formats['level_2'])
            sheet.write_number(row, 1, total_net, formats['level_2_num'])
            sheet.write_number(row, 2, total_tax, formats['level_2_num'])
            row += 2

        sheet.merge_range(row, 0, row, ncols - 1,
                          _('Generated by Odoo — Hilatech Export Accounting Report'),
                          formats['footer'])

        workbook.close()
        xlsx_bytes = output.getvalue()
        output.close()

        filename = helper._xlsx_build_filename(report_name, data_form)
        return helper._xlsx_build_attachment_action(filename, xlsx_bytes)
