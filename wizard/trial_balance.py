# -*- coding: utf-8 -*-
import io
from odoo import models, _
from odoo.exceptions import UserError
from odoo.tools.misc import get_lang

try:
    import xlsxwriter
except ImportError:
    xlsxwriter = None


class TrialBalanceXlsx(models.TransientModel):
    """Export XLSX pour le wizard Trial Balance."""

    _inherit = 'account.balance.report'

    def action_export_xlsx(self):
        self.ensure_one()
        if xlsxwriter is None:
            raise UserError(_("La bibliothèque Python 'xlsxwriter' est requise."))

        data = {'ids': self.env.context.get('active_ids', []),
                'model': self.env.context.get('active_model', 'ir.ui.menu'),
                'form': self.read(['date_from', 'date_to', 'journal_ids',
                                    'target_move', 'company_id',
                                    'display_account'])[0]}
        used_context = self._build_contexts(data)
        data['form']['used_context'] = dict(
            used_context, lang=get_lang(self.env).code)

        model = data['model']
        docs = self.env[model].browse(data.get('ids', []))
        accounts = docs if model == 'account.account' else self.env[
            'account.account'].search([])
        report_env = self.env['report.base_accounting_kit.report_trial_balance']
        account_lines = report_env.with_context(
            data['form'].get('used_context'))._get_accounts(
            accounts, data['form']['display_account'])

        account_lines.sort(
            key=lambda a: float(a.get('balance') or 0.0), reverse=True)

        journal_codes = [j.code for j in self.env['account.journal'].browse(
            data['form'].get('journal_ids') or [])]
        return self._build_xlsx(data['form'], account_lines, journal_codes)

    def _build_xlsx(self, data_form, account_lines, journal_codes):
        output = io.BytesIO()
        workbook = xlsxwriter.Workbook(output, {'in_memory': True})
        helper = self.env['hilatech.xlsx.report.helper']
        formats = helper._xlsx_get_formats(workbook)

        report_name = _('Trial Balance')
        sheet = workbook.add_worksheet(report_name[:31])
        sheet.hide_gridlines(2)

        sheet.set_column(0, 0, 15)
        sheet.set_column(1, 1, 45)
        sheet.set_column(2, 4, 18)
        ncols = 5

        info = helper._xlsx_standard_info_pairs(data_form, journal_codes)
        row = helper._xlsx_write_header(workbook, sheet, formats,
                                         report_name, info, ncols)

        headers = [_('Code'), _('Account'), _('Debit'), _('Credit'),
                   _('Balance')]
        row = helper._xlsx_write_table_header(sheet, row, headers, formats)

        total_debit = total_credit = total_balance = 0.0
        for acc in account_lines:
            sheet.write(row, 0, acc.get('code') or '', formats['detail'])
            sheet.write(row, 1, acc.get('name') or '', formats['detail'])
            debit = float(acc.get('debit') or 0.0)
            credit = float(acc.get('credit') or 0.0)
            balance = float(acc.get('balance') or 0.0)
            sheet.write_number(row, 2, debit, formats['detail_num'])
            sheet.write_number(row, 3, credit, formats['detail_num'])
            sheet.write_number(row, 4, balance, formats['detail_num'])
            total_debit += debit
            total_credit += credit
            total_balance += balance
            row += 1

        sheet.write(row, 0, '', formats['level_1'])
        sheet.write(row, 1, _('TOTAL'), formats['level_1'])
        sheet.write_number(row, 2, total_debit, formats['level_1_num'])
        sheet.write_number(row, 3, total_credit, formats['level_1_num'])
        sheet.write_number(row, 4, total_balance, formats['level_1_num'])
        row += 2

        sheet.merge_range(row, 0, row, ncols - 1,
                          _('Generated by Odoo — Hilatech Export Accounting Report'),
                          formats['footer'])

        workbook.close()
        xlsx_bytes = output.getvalue()
        output.close()

        filename = helper._xlsx_build_filename(report_name, data_form)
        return helper._xlsx_build_attachment_action(filename, xlsx_bytes)
