# -*- coding: utf-8 -*-
import io
from odoo import fields, models, _
from odoo.exceptions import UserError

try:
    import xlsxwriter
except ImportError:
    xlsxwriter = None


class AccountMoveXlsx(models.Model):
    """Export XLSX pour les factures client/fournisseur (account.move)."""

    _inherit = 'account.move'

    def action_export_xlsx(self):
        if xlsxwriter is None:
            raise UserError(_("La bibliothèque Python 'xlsxwriter' est requise."))
        if not self:
            raise UserError(_("Aucune facture sélectionnée."))

        helper = self.env['hilatech.xlsx.report.helper']

        output = io.BytesIO()
        workbook = xlsxwriter.Workbook(output, {'in_memory': True})
        formats = helper._xlsx_get_formats(workbook)

        is_multi = len(self) > 1
        if is_multi:
            report_name = _('Invoices')
            self._write_invoice_summary_sheet(workbook, formats, helper,
                                               report_name)
            sorted_moves = self.sorted(
                key=lambda m: float(m.amount_total_signed or 0.0),
                reverse=True)
            for move in sorted_moves:
                self._write_invoice_detail_sheet(workbook, formats, helper,
                                                  move)
        else:
            report_name = self.name or _('Invoice')
            self._write_invoice_detail_sheet(workbook, formats, helper, self)

        workbook.close()
        xlsx_bytes = output.getvalue()
        output.close()

        safe_name = (report_name or 'invoice').replace(' ', '_').replace(
            '/', '_').replace('\\', '_')
        filename = f'{safe_name}.xlsx'
        return helper._xlsx_build_attachment_action(filename, xlsx_bytes)

    def _write_invoice_summary_sheet(self, workbook, formats, helper,
                                      report_name):
        sheet = workbook.add_worksheet(_('Summary')[:31])
        sheet.hide_gridlines(2)

        widths = [16, 14, 30, 14, 14, 18, 18, 18]
        for col, w in enumerate(widths):
            sheet.set_column(col, col, w)
        ncols = len(widths)

        info = [
            (_('Number of invoices'), str(len(self))),
            (_('Printed on'),
             fields.Date.context_today(self).isoformat()),
        ]
        row = helper._xlsx_write_header(workbook, sheet, formats,
                                         report_name, info, ncols)

        headers = [_('Number'), _('Date'), _('Partner'), _('Type'),
                   _('Status'), _('Untaxed'), _('Tax'), _('Total')]
        row = helper._xlsx_write_table_header(sheet, row, headers, formats)

        total_untaxed = total_tax = total_total = 0.0
        sorted_moves = self.sorted(
            key=lambda m: float(m.amount_total_signed or 0.0),
            reverse=True)
        type_map = dict(self._fields['move_type'].selection)
        state_map = dict(self._fields['state'].selection)
        for move in sorted_moves:
            sheet.write(row, 0, move.name or '', formats['detail'])
            sheet.write(row, 1,
                        str(move.invoice_date or move.date or ''),
                        formats['detail'])
            sheet.write(row, 2, move.partner_id.name or '',
                        formats['detail'])
            sheet.write(row, 3, type_map.get(move.move_type, '') or '',
                        formats['detail'])
            sheet.write(row, 4, state_map.get(move.state, '') or '',
                        formats['detail'])
            sheet.write_number(row, 5,
                               float(move.amount_untaxed_signed or 0.0),
                               formats['detail_num'])
            sheet.write_number(row, 6,
                               float(move.amount_tax_signed or 0.0),
                               formats['detail_num'])
            sheet.write_number(row, 7,
                               float(move.amount_total_signed or 0.0),
                               formats['detail_num'])
            total_untaxed += float(move.amount_untaxed_signed or 0.0)
            total_tax += float(move.amount_tax_signed or 0.0)
            total_total += float(move.amount_total_signed or 0.0)
            row += 1

        sheet.merge_range(row, 0, row, 4, _('TOTAL'), formats['level_1'])
        sheet.write_number(row, 5, total_untaxed, formats['level_1_num'])
        sheet.write_number(row, 6, total_tax, formats['level_1_num'])
        sheet.write_number(row, 7, total_total, formats['level_1_num'])
        row += 2
        sheet.merge_range(row, 0, row, ncols - 1,
                          _('Generated by Odoo — Hilatech Export Accounting Report'),
                          formats['footer'])

    def _write_invoice_detail_sheet(self, workbook, formats, helper, move):
        move.ensure_one()
        safe_name = (move.name or 'INV').replace('/', '_').replace(
            '\\', '_')
        sheet = workbook.add_worksheet(safe_name[:31])
        sheet.hide_gridlines(2)

        widths = [40, 10, 14, 14, 14, 16]
        for col, w in enumerate(widths):
            sheet.set_column(col, col, w)
        ncols = len(widths)

        type_map = dict(move._fields['move_type'].selection)
        state_map = dict(move._fields['state'].selection)
        info = [
            (_('Number'), move.name or ''),
            (_('Type'), type_map.get(move.move_type, '') or ''),
            (_('Status'), state_map.get(move.state, '') or ''),
            (_('Partner'), move.partner_id.name or ''),
            (_('Invoice Date'),
             str(move.invoice_date) if move.invoice_date else '-'),
            (_('Due Date'),
             str(move.invoice_date_due) if move.invoice_date_due else '-'),
            (_('Reference'), move.ref or ''),
            (_('Currency'), move.currency_id.name or ''),
            (_('Printed on'),
             fields.Date.context_today(self).isoformat()),
        ]
        report_name = f"{type_map.get(move.move_type, _('Invoice'))} - {move.name or ''}"
        row = helper._xlsx_write_header(workbook, sheet, formats,
                                         report_name, info, ncols)

        headers = [_('Description'), _('Qty'), _('Unit Price'),
                   _('Discount %'), _('Taxes'), _('Subtotal')]
        row = helper._xlsx_write_table_header(sheet, row, headers, formats)

        lines = move.invoice_line_ids.sorted(
            key=lambda l: float(l.price_subtotal or 0.0), reverse=True)
        for line in lines:
            taxes = ', '.join(line.tax_ids.mapped('name'))
            sheet.write(row, 0, line.name or '', formats['detail'])
            sheet.write_number(row, 1, float(line.quantity or 0.0),
                               formats['detail_num'])
            sheet.write_number(row, 2, float(line.price_unit or 0.0),
                               formats['detail_num'])
            sheet.write_number(row, 3, float(line.discount or 0.0),
                               formats['detail_num'])
            sheet.write(row, 4, taxes, formats['detail'])
            sheet.write_number(row, 5, float(line.price_subtotal or 0.0),
                               formats['detail_num'])
            row += 1

        sheet.merge_range(row, 0, row, ncols - 2, _('Untaxed Amount'),
                          formats['level_2'])
        sheet.write_number(row, ncols - 1,
                           float(move.amount_untaxed or 0.0),
                           formats['level_2_num'])
        row += 1
        sheet.merge_range(row, 0, row, ncols - 2, _('Taxes'),
                          formats['level_2'])
        sheet.write_number(row, ncols - 1, float(move.amount_tax or 0.0),
                           formats['level_2_num'])
        row += 1
        sheet.merge_range(row, 0, row, ncols - 2, _('Total'),
                          formats['level_1'])
        sheet.write_number(row, ncols - 1, float(move.amount_total or 0.0),
                           formats['level_1_num'])
        row += 2
        sheet.merge_range(row, 0, row, ncols - 1,
                          _('Generated by Odoo — Hilatech Export Accounting Report'),
                          formats['footer'])
